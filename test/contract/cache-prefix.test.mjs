import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";
import { answer, compactions, createCompactionHost } from "../helpers/codex-compaction.mjs";
import { temporaryDirectory } from "../helpers/temp-dir.mjs";

test("cache prefix opt-in observes transformed foreground requests and pairs successful provider usage", async t => {
  const dir = temporaryDirectory(t, "metis-cache-prefix-");
  const transform = join(dir, "trace-transform.ts");
  writeFileSync(transform, `export default function(pi) {
    let count = 0;
    pi.on("before_provider_request", ({ payload }) => ({ ...payload, instructions: "private-transform-" + ++count }));
  }`);
  const extension = fileURLToPath(new URL("../../extensions/cache-prefix.ts", import.meta.url));
  let requests = 0;
  const h = await createCompactionHost(t, { extensionPaths: [extension, transform], normalResponse: () => {
    requests++;
    if (requests === 3) return Response.json({ error: { message: "private failure" } }, { status: 400 });
    return answer(requests === 2 ? 80 : 0);
  } });
  const command = (suffix = "") => h.session.prompt(`/cache-prefix ${suffix}`);
  const notice = () => h.notices.at(-1);
  await h.session.prompt("private-history-before-opt-in");
  await command();
  assert.match(notice(), /diagnostics off/);
  await command("on");
  await h.session.prompt("private-first-captured-prompt");
  const baseline = h.bodies.at(-1);
  assert.match(baseline.instructions, /^private-transform-/);
  await h.session.compact();
  assert.equal(h.bodies.at(-1).input.at(-1).type, "compaction_trigger");
  await command();
  assert.match(notice(), /Captured 1 of 2/);
  await h.session.prompt("private-failure-fixture");
  await command();
  assert.match(notice(), /Captured 1 of 2/, "failed requests do not substitute for a usage receipt");
  await h.session.prompt("private-after-compaction");
  assert.equal(requests, 4);
  assert.ok(h.bodies.at(-1).input.some(item => item.type === "compaction"));
  await command();
  assert.match(notice(), /Top-level system prompt changed/, "the observer sees the final transformer, even if loaded first");
  assert.notDeepEqual(h.bodies.at(-1).input[0], baseline.input[0]);
  assert.match(notice(), /First changed input item: #1\b/);
  assert.match(notice(), /Checkpoint items changed \(0 → 1\)/);
  assert.match(notice(), /80\/100 cached input tokens → 0\/100 cached input tokens/);
  assert.doesNotMatch(notice(), /private-|opaque-|offline-test|ORIGINAL USER/);
  assert.doesNotMatch(JSON.stringify(h.sm.getBranch()), /Cache prefix:|provider_request_prepared/);
  await h.session.navigateTree(compactions(h).at(-1).id, { summarize: false });
  await command();
  assert.match(notice(), /Captured 0 of 2/, "navigating to another leaf invalidates the baseline");
  await h.session.prompt("private-fresh-baseline");
  await command();
  assert.match(notice(), /Captured 1 of 2/);
  await command("off");
  await command("on");
  await command();
  assert.match(notice(), /Captured 0 of 2/);
});
