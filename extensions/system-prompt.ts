import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { getAgentDir, getDocsPath, getExamplesPath, getReadmePath, type ExtensionAPI } from "@earendil-works/pi-coding-agent";

export default function systemPrompt(pi: ExtensionAPI): void {
  const agentDir = getAgentDir();
  const guidePath = join(agentDir, "PI_Documentation_Guide.md");
  const marker = "<!-- Generated by metis-pi; remove this line to keep local edits. -->\n";
  const guide = marker + readFileSync(new URL("../docs/PI_Documentation_Guide.md", import.meta.url), "utf8")
    .replaceAll("{{PI_README}}", getReadmePath())
    .replaceAll("{{PI_DOCS}}", getDocsPath())
    .replaceAll("{{PI_EXAMPLES}}", getExamplesPath());
  const previous = existsSync(guidePath) ? readFileSync(guidePath, "utf8") : undefined;
  if (previous !== guide && (previous === undefined || previous.startsWith(marker))) {
    mkdirSync(agentDir, { recursive: true });
    writeFileSync(guidePath, guide, { mode: 0o600 });
  }

  pi.on("before_agent_start", (event) => {
    const options = event.systemPromptOptions;
    if (options.customPrompt || options.forceSystemPrompt !== undefined) return;
    options.sections.docs = "Pi documentation (read only when the user asks about Pi itself, its SDK, extensions, themes, skills, or TUI):\n" +
      `- Read ${guidePath} for documentation locations and usage guidance.`;
  });
}
